import re

# ==================================================================
# Единый источник паттернов "количество" для всего проекта.
# ==================================================================

# Каждый паттерн привязан к "нормализованной" единице -
# unit сохраняется в результате, чтобы дальше (в ExcelNameBuilder)
# можно было правильно склонять "пара/пары/пар", а не потерять,
# что это были именно пары, а не штуки.
_PATTERNS = [
    (r"(\d+)\s*шт\.?", "шт"),
    (r"(\d+)\s*штук[аи]?", "шт"),
    (r"(\d+)\s*ед\.?", "шт"),
    (r"(\d+)\s*единиц[аы]?", "шт"),
    (r"комплект\s+из\s+(\d+)", "комплект"),
    (r"набор\s+из\s+(\d+)", "набор"),
    (r"(\d+)\s*pcs", "шт"),
    (r"(\d+)\s*pieces", "шт"),
    (r"(\d+)\s*пар[аы]?", "пар"),
    (r"(\d+)\s*комплект(?:а|ов)?", "комплект"),
    (r"(\d+)\s*набор(?:а|ов)?", "набор"),
]

# ------------------------------------------------------------------
# НАБОР ИЗ РАЗНЫХ ПРЕДМЕТОВ ("Комплектация: пылесос, насадка-щётка,
# шланг - 2 предмета") vs ПОВТОР ОДНОГО И ТОГО ЖЕ ТОВАРА
# ("Количество в упаковке: 2").
# Эвристика: если в перечислении встречается >=2 РАЗНЫХ слов/фраз
# (после отбрасывания самих счётных конструкций вида "N шт") - это
# описание СОСТАВА набора, а не количество экземпляров товара, и
# число из него не должно становиться card.quantity.
# ------------------------------------------------------------------

_COUNT_TOKEN_PATTERN = re.compile(
    r"\d+\s*(?:шт\.?|штук[аи]?|предмет\w*|деталь\w*|элемент\w*|позици\w*)",
    re.IGNORECASE,
)


def is_heterogeneous_kit(text: str) -> bool:
    """True, если текст перечисляет РАЗНЫЕ предметы набора
    (пылесос, насадка, шланг), а не количество ОДНОГО и того же
    товара."""

    if not text:
        return False

    text = str(text)
    parts = re.split(r"\s*[,;/]\s*|\s+и\s+", text)

    distinct_items = set()

    for part in parts:

        cleaned = _COUNT_TOKEN_PATTERN.sub("", part).strip(" .-\t")
        cleaned = re.sub(r"\s+", " ", cleaned).lower()

        if len(cleaned) >= 3:
            distinct_items.add(cleaned)

    return len(distinct_items) >= 2


_KIT_MARKER_PATTERN = re.compile(
    r"(?:комплектация|состав\s+набора|состав\s+комплекта|в\s+комплекте)"
    r"\s*[:\-]\s*([^\n\r.]+)",
    re.IGNORECASE,
)


def strip_heterogeneous_kit_segments(text: str) -> str:
    """Для свободного текста (title/description), где явно помечен
    состав набора ('В комплекте: пылесос, щётка-насадка') - вырезает
    именно этот сегмент, если он описывает РАЗНЫЕ предметы, чтобы
    число из него (например, '2 предмета') не попало в
    extract_quantity() как количество основного товара. Не трогает
    обычные перечисления без такой явной пометки ('Носки, 5 пар,
    хлопок' остаётся как есть)."""

    if not text:
        return text

    def _replace(match):
        segment = match.group(1)
        if is_heterogeneous_kit(segment):
            return " "
        return match.group(0)

    return _KIT_MARKER_PATTERN.sub(_replace, str(text))


def extract_quantity(text: str) -> str:
    """
    Ищет упоминание количества в произвольном тексте
    (заголовок, описание, значение спека - неважно).
    Возвращает "N <unit>" (unit в {"шт","пар","компл"}) или ""
    если не найдено. "1 шт" сознательно отбрасывается -
    штучный товар не нужно помечать в названии.

    ВАЖНО: эта функция не решает сама, является ли текст описанием
    состава разнородного набора (для этого есть is_heterogeneous_kit)
    - применять её к значению поля "Комплектация" нужно вызывающей
    стороне через is_heterogeneous_kit(), т.к. здесь такая проверка
    ломала бы обычные случаи вроде "Носки женские, 5 пар, хлопок"
    (запятые между обычными описательными словами - это не разные
    предметы одного набора).
    """

    if not text:
        return ""

    text = str(text).strip().lower()

    for pattern, unit in _PATTERNS:

        match = re.search(pattern, text)

        if not match:
            continue

        number = int(match.group(1))

        if number < 2:
            return ""

        return f"{number} {unit}"

    return ""