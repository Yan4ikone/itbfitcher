import re

# ==================================================================
# Единый источник паттернов "количество" для всего проекта.
# ==================================================================

# Каждый паттерн привязан к "нормализованной" единице -
# unit сохраняется в результате, чтобы дальше (в ExcelNameBuilder)
# можно было правильно склонять "пара/пары/пар", а не потерять,
# что это были именно пары, а не штуки.
_PATTERNS = [
    (r"(?P<num>\d+)\s*шт\.?", "шт"),
    (r"(?P<num>\d+)\s*штук[аи]?", "шт"),
    (r"(?P<num>\d+)\s*ед\.?", "шт"),
    (r"(?P<num>\d+)\s*единиц[аы]?", "шт"),
    (r"комплект\s+из\s+(?P<num>\d+)", "комплект"),
    (r"набор\s+из\s+(?P<num>\d+)", "набор"),
    (r"(?P<num>\d+)\s*pcs", "шт"),
    (r"(?P<num>\d+)\s*pieces", "шт"),
    (r"(?P<num>\d+)\s*пар[аы]?", "пар"),
    (r"(?P<num>\d+)\s*комплект(?:а|ов)?", "комплект"),
    (r"(?P<num>\d+)\s*набор(?:а|ов)?", "набор"),
    # Фолбэк: "Количество в упаковке: 3" / "Кол-во: 3" - голое число
    # без единицы измерения рядом, но с однозначной подписью поля.
    # Намеренно НЕ включает "комплект"/"набор" - для них та же самая
    # подпись может означать состав РАЗНОРОДНОГО набора (см.
    # is_heterogeneous_kit/strip_heterogeneous_kit_segments), а
    # "количество"/"в упаковке" всегда про число экземпляров товара.
    #
    # ВАЖНО: "Количество листов: 100" / "Кол-во страниц: 96" - это
    # атрибут ОДНОГО товара (у альбома 100 листов), а не число
    # экземпляров товара в упаковке. Раньше это давало "100 шт" -
    # альбом с сотней листов ошибочно помечался как "100 штук
    # альбомов". Слово, называющее то, что считается (лист/страница/
    # деталь/элемент и т.п.), стоит МЕЖДУ ключевым словом и числом -
    # проверяем именно этот промежуток через именованную группу
    # "between" (см. проверку в extract_quantity).
    (
        r"(?P<before>\D{0,15}?)"
        r"(?:количество|кол-во|кол\s+во|в\s+упаковке)"
        r"(?P<between>\D{0,15}?)(?P<num>\d+)",
        "шт",
    ),
]

# Слова, которые называют счётные КОМПОНЕНТЫ/части/атрибуты товара
# (листы альбома, детали конструктора, секции шкафа, полки, ящики и
# т.п.), а не количество экземпляров самого товара в упаковке. Раньше:
# - "Количество листов: 100" (у альбома 100 листов) ошибочно давало
#   "100 шт" - альбом помечался как "100 штук альбомов";
# - "Количество секций: 3" (шкаф из 3 секций) ошибочно давало "3 шт";
# - "Количество деталей: 1056" (конструктор из 1056 деталей) ошибочно
#   давало "1056 шт".
# ЕДИНЫЙ список слов-исключений - используется и в _NOT_PRODUCT_UNIT
# (для "между"-текста в свободных фразах вида "Количество листов в
# блокноте: 100"), и в is_component_count_key() (для названия
# спек-поля в card_builder.py, когда значение - голое число без
# единицы измерения рядом).
_COMPONENT_COUNT_WORDS_RAW = (
    r"лист|страниц|стран|деталь|детал|элемент|позици|"
    r"секци|полк\w*|полок\b|полоч\w*|ящик|отсек|отделени|дверц|дверь|"
    r"карман|модул|ячейк|звен|ступен|уровен|ярус|тумб|блок"
)

_NOT_PRODUCT_UNIT = re.compile(
    _COMPONENT_COUNT_WORDS_RAW + r"|стр\.|л\."
    # ДОБАВЛЕНО: единицы измерения размера/веса товара (мм/см/кг/мл/г) -
    # реальный случай: "Высота товара в упаковке, мм: 20" ошибочно
    # давало "20 шт" - фолбэк-паттерн ниже цепляется за "в упаковке" и
    # берёт первое число ПОСЛЕ, не разбирая, что стоит МЕЖДУ ("в
    # упаковке, мм:") - это подпись единицы измерения, а не пустой
    # промежуток перед числом штук. См. также группу "before" в самом
    # паттерне - проверяет, что стоит ПЕРЕД "в упаковке" (высота/
    # длина/ширина/...).
    r"|мм|см|кг|мл|\bг\b",
    re.IGNORECASE,
)


def is_component_count_key(key: str) -> bool:
    """True, если название спек-поля ("Количество секций",
    "Количество листов", "Кол-во деталей") указывает на счёт
    КОМПОНЕНТОВ/частей/атрибутов товара, а не экземпляров самого
    товара - см. _COMPONENT_COUNT_WORDS_RAW."""

    if not key:
        return False

    return bool(re.search(_COMPONENT_COUNT_WORDS_RAW, str(key), re.IGNORECASE))

# Слова физических размеров/веса товара - если что-то из этого стоит
# СРАЗУ ПЕРЕД "в упаковке" ("Высота товара В УПАКОВКЕ, мм: 20"), это
# явно размерное поле упаковки, а не "Количество в упаковке: N" - число
# после него не должно становиться card.quantity ни при каких единицах
# измерения (перестраховка на случай, если подпись единицы измерения
# вообще отсутствует в тексте).
_PACKAGE_DIMENSION_WORDS = (
    "высота",
    "длина",
    "ширина",
    "глубина",
    "диаметр",
    "вес",
    "масса",
)

# ------------------------------------------------------------------
# НАБОР ИЗ РАЗНЫХ ПРЕДМЕТОВ ("Комплектация: пылесос, насадка-щётка,
# шланг - 2 предмета") vs ПОВТОР ОДНОГО И ТОГО ЖЕ ТОВАРА
# ("Количество в упаковке: 2").
# Эвристика: если в перечислении встречается >=2 РАЗНЫХ слов/фраз
# (после отбрасывания самих счётных конструкций вида "N шт") - это
# описание СОСТАВА набора, а не количество экземпляров товара, и
# число из него не должно становиться card.quantity.
# ------------------------------------------------------------------

_COUNT_TOKEN_PATTERN = re.compile(
    r"\d+\s*(?:шт\.?|штук[аи]?|предмет\w*|деталь\w*|элемент\w*|позици\w*)",
    re.IGNORECASE,
)


def is_heterogeneous_kit(text: str) -> bool:
    """True, если текст перечисляет РАЗНЫЕ предметы набора
    (пылесос, насадка, шланг), а не количество ОДНОГО и того же
    товара."""

    if not text:
        return False

    text = str(text)
    parts = re.split(r"\s*[,;/]\s*|\s+и\s+", text)

    distinct_items = set()

    for part in parts:

        cleaned = _COUNT_TOKEN_PATTERN.sub("", part).strip(" .-\t")
        cleaned = re.sub(r"\s+", " ", cleaned).lower()

        if len(cleaned) >= 3:
            distinct_items.add(cleaned)

    return len(distinct_items) >= 2


_KIT_MARKER_PATTERN = re.compile(
    r"(?:комплектация|состав\s+набора|состав\s+комплекта|в\s+комплекте)"
    r"\s*[:\-]\s*([^\n\r.]+)",
    re.IGNORECASE,
)


def strip_heterogeneous_kit_segments(text: str) -> str:
    """Для свободного текста (title/description), где явно помечен
    состав набора ('В комплекте: пылесос, щётка-насадка') - вырезает
    именно этот сегмент, если он описывает РАЗНЫЕ предметы, чтобы
    число из него (например, '2 предмета') не попало в
    extract_quantity() как количество основного товара. Не трогает
    обычные перечисления без такой явной пометки ('Носки, 5 пар,
    хлопок' остаётся как есть)."""

    if not text:
        return text

    def _replace(match):
        segment = match.group(1)
        if is_heterogeneous_kit(segment):
            return " "
        return match.group(0)

    return _KIT_MARKER_PATTERN.sub(_replace, str(text))


def extract_quantity(text: str) -> str:
    """
    Ищет упоминание количества в произвольном тексте
    (заголовок, описание, значение спека - неважно).
    Возвращает "N <unit>" (unit в {"шт","пар","компл"}) или ""
    если не найдено. "1 шт" сознательно отбрасывается -
    штучный товар не нужно помечать в названии.

    ВАЖНО: эта функция не решает сама, является ли текст описанием
    состава разнородного набора (для этого есть is_heterogeneous_kit)
    - применять её к значению поля "Комплектация" нужно вызывающей
    стороне через is_heterogeneous_kit(), т.к. здесь такая проверка
    ломала бы обычные случаи вроде "Носки женские, 5 пар, хлопок"
    (запятые между обычными описательными словами - это не разные
    предметы одного набора).
    """

    if not text:
        return ""

    text = str(text).strip().lower()

    for pattern, unit in _PATTERNS:

        match = re.search(pattern, text)

        if not match:
            continue

        groups = match.groupdict()

        between = groups.get("between")
        if between and _NOT_PRODUCT_UNIT.search(between):
            continue

        before = groups.get("before")
        if before and any(
            word in before for word in _PACKAGE_DIMENSION_WORDS
        ):
            continue

        number = int(groups["num"])

        if number < 2:
            return ""

        return f"{number} {unit}"

    return ""